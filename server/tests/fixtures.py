def make_exam_pdf(items=EXAM) -> bytes:  # noqa: ANN001
    doc = pymupdf.open()
    page = doc.new_page()
    y = 60.0
    for item in items:
        if item is None:
            page = doc.new_page()
            y = 60.0
            continue
        text, size = item
        # 用文本框自动换行，模拟真实试卷中长题干跨行的情况
        rect = pymupdf.Rect(60, y, 535, y + 200)
        left = page.insert_textbox(rect, text, fontname="china-s", fontsize=size, lineheight=1.5)
        used = 200 - left if left >= 0 else 200
        y += used + 6
    return doc.tobytes()


def make_scanned_pdf() -> bytes:
    """只有图片、没有文字层的 PDF，模拟扫描件。"""
    doc = pymupdf.open()
    page = doc.new_page()
    pix = pymupdf.Pixmap(pymupdf.csRGB, pymupdf.IRect(0, 0, 200, 200), False)
    pix.clear_with(200)
    page.insert_image(page.rect, pixmap=pix)
    return doc.tobytes()
